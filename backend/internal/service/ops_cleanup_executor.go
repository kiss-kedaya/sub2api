// opsCleanupPlan 把"保留天数"翻译成具体的清理动作。
//   - days < 0  → 跳过该项清理（ok=false），保留兼容老数据
//   - days == 0 → TRUNCATE TABLE（O(1) 全清），truncate=true
//   - days > 0  → 批量 DELETE 早于 now-N天 的行，cutoff = now - N 天
func opsCleanupPlan(now time.Time, days int) (cutoff time.Time, truncate, ok bool) {
	if days < 0 {
		return time.Time{}, false, false
	}
	if days == 0 {
		return time.Time{}, true, true
	}
	return now.AddDate(0, 0, -days), false, true
}

func opsCleanupRunOne(
	ctx context.Context,
	db *sql.DB,
	truncate bool,
	cutoff time.Time,
	table, timeCol string,
	castDate bool,
	batchSize int,
) (int64, error) {
	if truncate {
		return truncateOpsTable(ctx, db, table)
	}
	return deleteOldRowsByCTID(ctx, db, table, timeCol, cutoff, batchSize, castDate)
}

// opsCleanupDeleteBatchSQL builds a ctid + ARRAY(subquery) batch DELETE so
// Postgres uses a Tid Scan on the outer DELETE and avoids ORDER BY id sorts or
// PK probes when pruning heavily indexed tables such as ops_error_logs.
func opsCleanupDeleteBatchSQL(table, timeColumn string, castCutoffToDate bool) string {
	where := fmt.Sprintf("%s < $1", timeColumn)
	if castCutoffToDate {
		where = fmt.Sprintf("%s < $1::date", timeColumn)
	}
	return fmt.Sprintf(`
DELETE FROM %[1]s
WHERE ctid = ANY(ARRAY(
  SELECT ctid FROM %[1]s
  WHERE %[2]s
  LIMIT $2
))
`, table, where)
}

func deleteOldRowsByCTID(
	ctx context.Context,
	db *sql.DB,
	table string,
	timeColumn string,
	cutoff time.Time,
	batchSize int,
	castCutoffToDate bool,
) (int64, error) {
	if db == nil {
		return 0, nil
	}
	if ctx == nil {
		ctx = context.Background()
	}
	if batchSize <= 0 {
		batchSize = opsCleanupBatchSize
	}

	q := opsCleanupDeleteBatchSQL(table, timeColumn, castCutoffToDate)

	var total int64
	for {
		if err := ctx.Err(); err != nil {
			return total, err
		}
		batchCtx := ctx
		var cancel context.CancelFunc
		if opsCleanupBatchTimeout > 0 {
			batchCtx, cancel = context.WithTimeout(ctx, opsCleanupBatchTimeout)
		}
		res, err := db.ExecContext(batchCtx, q, cutoff, batchSize)
		if cancel != nil {
			cancel()
		}
		if err != nil {
			if isMissingRelationError(err) {
				return total, nil
			}
			return total, err
		}
		affected, err := res.RowsAffected()
		if err != nil {
			return total, err
		}
		total += affected
		if affected == 0 {
			break
		}
	}
	return total, nil
}

// truncateOpsTable 用 TRUNCATE TABLE 清空指定表，先 SELECT COUNT(*) 取得清空前行数用于 heartbeat。
func truncateOpsTable(ctx context.Context, db *sql.DB, table string) (int64, error) {
	if db == nil {
		return 0, nil
	}
	var count int64
	if err := db.QueryRowContext(ctx, fmt.Sprintf("SELECT COUNT(*) FROM %s", table)).Scan(&count); err != nil {
		if isMissingRelationError(err) {
			return 0, nil
		}
		return 0, fmt.Errorf("count %s: %w", table, err)
	}
	if count == 0 {
		return 0, nil
	}
	if _, err := db.ExecContext(ctx, fmt.Sprintf("TRUNCATE TABLE %s", table)); err != nil {
		if isMissingRelationError(err) {
			return 0, nil
		}
		return 0, fmt.Errorf("truncate %s: %w", table, err)
	}
	return count, nil
}

func isMissingRelationError(err error) bool {
	if err == nil {
		return false
	}
	s := strings.ToLower(err.Error())
	return strings.Contains(s, "does not exist") && strings.Contains(s, "relation")
}
