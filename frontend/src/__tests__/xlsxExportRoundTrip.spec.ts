import { describe, expect, it } from 'vitest'

describe('usage workbook export with the official patched SheetJS release', () => {
  it('writes paginated rows to a real XLSX file and preserves data on readback', async () => {
    const XLSX = await import('xlsx')
    expect(XLSX.version).toBe('0.20.3')

    const headers = ['用户', '输入 Token', '实际费用', '请求 ID', '备注']
    const firstPage = [
      ['fixture@example.com', 1234, '0.012345', 'client:export-fixture', '中文、逗号与\n换行'],
      ['=HYPERLINK("https://example.com", "text")', 0, '0.000000', '+not-a-formula', '<script>fixture</script>']
    ]
    const lastPage = [['second@example.com', 5678, '1.234567', '@fixture', 'Unicode ✓']]
    const sheet = XLSX.utils.aoa_to_sheet([headers])
    XLSX.utils.sheet_add_aoa(sheet, firstPage, { origin: -1 })
    XLSX.utils.sheet_add_aoa(sheet, lastPage, { origin: -1 })
    const workbook = XLSX.utils.book_new()
    XLSX.utils.book_append_sheet(workbook, sheet, 'Usage')

    const output = XLSX.write(workbook, { bookType: 'xlsx', type: 'array' }) as ArrayBuffer
    // XLSX is a ZIP container. Read only these locally generated bytes; no
    // user-supplied workbook is accepted anywhere in the application.
    expect([...new Uint8Array(output).slice(0, 4)]).toEqual([0x50, 0x4b, 0x03, 0x04])
    const reopened = XLSX.read(output, { type: 'array' })
    expect(reopened.SheetNames).toEqual(['Usage'])
    expect(XLSX.utils.sheet_to_json(reopened.Sheets.Usage!, { header: 1, raw: true })).toEqual([
      headers, ...firstPage, ...lastPage
    ])
    // Names and identifiers beginning with formula markers remain literal
    // string cells instead of becoming spreadsheet formulas.
    expect(reopened.Sheets.Usage!.A3).toMatchObject({ t: 's', v: firstPage[1]![0] })
    expect(reopened.Sheets.Usage!.A3.f).toBeUndefined()
    expect(reopened.Sheets.Usage!.D3.f).toBeUndefined()
    expect(reopened.Sheets.Usage!.D4.f).toBeUndefined()
  })
})
